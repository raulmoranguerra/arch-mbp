#!/usr/bin/env bash
# Run as your normal user after the first boot, with network up (nmtui for Wi-Fi).
# Add INSTALL_CAMERA=1 to also build the FaceTime HD camera driver (downloads Apple firmware).
set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

# Per-machine defaults: Air gets the black and white theme at scale 1, everything else Gruvbox at scale 2.
PRODUCT="$(cat /sys/class/dmi/id/product_name 2>/dev/null || echo unknown)"
case "$PRODUCT" in
  MacBookAir*) DEFAULT_THEME=mono;    DEFAULT_SCALE=1 ;;
  *)           DEFAULT_THEME=catppuccin; DEFAULT_SCALE=2 ;;
esac
THEME="${THEME:-$DEFAULT_THEME}"
SCALE="${SCALE:-$DEFAULT_SCALE}"
[ -d "$REPO/stow/theme-$THEME" ] || { echo "Unknown theme: $THEME"; exit 1; }
echo "Model: $PRODUCT  Theme: $THEME  Scale: $SCALE"

PKGS=(
  hyprland hyprlock hypridle hyprpaper waybar kitty rofi dunst
  fish zoxide yazi
  grim slurp wl-clipboard brightnessctl playerctl
  pipewire pipewire-pulse pipewire-alsa wireplumber
  xdg-desktop-portal-wlr xdg-desktop-portal-gtk polkit xorg-xwayland
  mesa libva-intel-driver libva-utils
  ttf-iosevka-nerd inter-font ttf-jetbrains-mono-nerd noto-fonts noto-fonts-emoji papirus-icon-theme
  tlp thermald zram-generator earlyoom greetd greetd-tuigreet
  openssh avahi nss-mdns
  stow starship fastfetch btop neovim bash-completion man-db firefox mpv
)
sudo pacman -Syu --needed --noconfirm "${PKGS[@]}"

# AUR helper (prebuilt binary, avoids compiling Rust on the old CPU)
if ! command -v paru >/dev/null; then
  tmp="$(mktemp -d)"
  git clone https://aur.archlinux.org/paru-bin.git "$tmp/paru-bin"
  (cd "$tmp/paru-bin" && makepkg -si --noconfirm)
  rm -rf "$tmp"
fi

AUR=(mbpfan-git)
[ "${INSTALL_CAMERA:-0}" = "1" ] && AUR+=(facetimehd-dkms facetimehd-firmware)
paru -S --needed --noconfirm "${AUR[@]}" || \
  echo "WARNING: some AUR packages failed. Check names with: paru -Ss mbpfan"

# System tuning
sudo install -Dm644 "$REPO/system/etc/tlp.d/10-mbp.conf"                      /etc/tlp.d/10-mbp.conf
sudo install -Dm644 "$REPO/system/etc/systemd/zram-generator.conf"            /etc/systemd/zram-generator.conf
sudo install -Dm644 "$REPO/system/etc/sysctl.d/99-zram.conf"                  /etc/sysctl.d/99-zram.conf
sudo install -Dm644 "$REPO/system/etc/systemd/journald.conf.d/size.conf"      /etc/systemd/journald.conf.d/size.conf
sudo install -Dm755 "$REPO/system/usr/local/bin/wm-session"                 /usr/local/bin/wm-session
sudo install -Dm644 "$REPO/system/etc/greetd/config.toml"                     /etc/greetd/config.toml
sudo install -Dm644 "$REPO/system/etc/ssh-hardening.conf"                     /etc/ssh/sshd_config.d/10-hardening.conf
install -Dm600 "$REPO/system/ssh/authorized_keys" "$HOME/.ssh/authorized_keys"
chmod 700 "$HOME/.ssh"
grep -q mdns_minimal /etc/nsswitch.conf || sudo sed -i 's/ resolve / mdns_minimal [NOTFOUND=return] resolve /' /etc/nsswitch.conf
sudo systemctl daemon-reload
sudo systemctl mask systemd-rfkill.service systemd-rfkill.socket
sudo systemctl enable tlp thermald earlyoom
sudo systemctl enable sshd avahi-daemon
sudo systemctl enable greetd   # TUI login (tuigreet) on tty1, replaces getty@tty1
# Start without waiting: one of these can block for a long time, and they all start on the next boot anyway.
for s in tlp thermald earlyoom; do sudo systemctl start --no-block "$s" || true; done
sudo systemctl enable mbpfan 2>/dev/null || sudo systemctl enable mbpfan.service || true
sudo systemctl start --no-block systemd-zram-setup@zram0.service || true
sudo sysctl --system >/dev/null

# Let brightnessctl change the backlight without root (takes effect at next login)
sudo usermod -aG video "$USER"

# Dotfiles: move aside anything that would conflict, then symlink with stow
mkdir -p "$HOME/Pictures"
for f in .bashrc .bash_profile; do
  [ -e "$HOME/$f" ] && [ ! -L "$HOME/$f" ] && mv "$HOME/$f" "$HOME/$f.bak"
done
mkdir -p "$HOME/.config/hypr"
# Keyboard layout follows the console keymap chosen at install time (default us if unset)
KB="$(. /etc/vconsole.conf 2>/dev/null; echo "${KEYMAP:-us}")"
printf -- '-- Generated by 03-post.sh for %s\nhl.monitor({ output = "eDP-1", mode = "preferred", position = "auto", scale = %s })\nhl.config({ input = { kb_layout = "%s" } })\n' "$PRODUCT" "$SCALE" "$KB" > "$HOME/.config/hypr/host.lua"
stow --no-folding -d "$REPO/stow" -t "$HOME" common "theme-$THEME"
chmod +x "$HOME/.local/bin/shot" "$HOME/.config/rofi/"*.sh || true
# Fish as the login shell (greeting, starship prompt, zoxide)
sudo usermod -s /usr/bin/fish "$USER" || true

echo
echo "Done. Reboot: a text login (tuigreet) appears on tty1 and starts Hyprland."
echo "Check power: sudo tlp-stat -s ; sudo powertop (optional) ; systemd-analyze"
